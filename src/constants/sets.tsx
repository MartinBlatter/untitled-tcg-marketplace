// This is async and will be used by client components with React.use()
export const getSets = async (): Promise<string[]> => {
    try {
        const dbSets = await fetchSets();
        if (dbSets && dbSets.length > 0) {
            return dbSets.map((set) => set.code);
        }
        return staticSets;
    } catch (error) {
        console.error('Error fetching sets from database, using static sets:', error);
        return staticSets;
    }
};

// For backward compatibility
export const sets = staticSets;

// Export set data with both code and name
export const getSetData = async (): Promise<SetType[]> => {
    try {
        const dbSets = await fetchSets();
        if (dbSets && dbSets.length > 0) {
            return dbSets;
        }
        return [];
    } catch (error) {
        console.error('Error fetching set data from database:', error);
        return [];
    }
};
